
import logging
import re

from telegram import Update
from telegram.constants import ParseMode
from telegram.error import TelegramError
from telegram.ext import ContextTypes

logger = logging.getLogger(__name__)

# Принимает: Правила, Правила чата, /правила, Правила!
RULES_RE = re.compile(
    r"(?i)^\s*/?правила(?:\s+чата)?\s*[.!?]*\s*$"
)

RULES_TEXT = """<b>ПРАВИЛА ЧАТА</b>

<b>1. НАКАЗАНИЯ</b>
• Мут — запрет писать на время.
• Предупреждение действует 5 дней; 3 действующих предупреждения могут привести к бану.
• Бан — исключение; экстремальный бан — немедленное исключение за тяжкие нарушения.
Администрация может усилить наказание.

<b>2. ОБЩЕНИЕ</b>
Запрещены оскорбления участников и близких; травля и преследование; провокации и разжигание конфликтов; флуд, спам и массовые упоминания; злоупотребление капсом; навязчивость после просьбы остановиться; ложные обвинения и попрошайничество.
Наказание: замечание, мут, предупреждение или бан.

<b>3. ЗАПРЕЩЁННЫЙ КОНТЕНТ</b>
Запрещены порнография и сексуальные материалы с несовершеннолетними; расчленение, пытки и шок-контент; угрозы и призывы к насилию; нацизм, экстремизм, расовая ненависть и дискриминация; оскорбление религии; призывы к самоубийству и самоповреждению; пропаганда жестокости к животным.
Наказание: мут, бан или экстремальный бан.

<b>4. НИКОТИН И ЗАПРЕЩЁННЫЕ ТОВАРЫ</b>
Запрещены реклама, продажа, покупка, поиск продавцов и продвижение снюса, никотиновых пакетиков, сигарет, табака, вейпов, жидкостей, картриджей, наркотиков, опасных веществ, нелегальных препаратов и оружия.
Хвастовство наличием или употреблением такой продукции также может повлечь наказание. Нейтральное информационное обсуждение само по себе не является нарушением.
Наказание: удаление, предупреждение, мут или бан.

<b>5. РЕКЛАМА И ССЫЛКИ</b>
Запрещены реклама чатов, каналов, сайтов и услуг без разрешения; самореклама; реферальные ссылки без разрешения; фишинг и вредоносные ссылки; массовые рекламные упоминания.
Наказание: мут или бан.

<b>6. МОШЕННИЧЕСТВО</b>
Запрещены обман ради денег, монет или имущества; мошенничество при сделках; фальшивые сборы; кража аккаунтов и выманивание кодов; использование багов бота.
Наказание: бан или экстремальный бан.

<b>7. ПРИВАТНОСТЬ</b>
Запрещены публикация личных данных без согласия; доксинг; шантаж; слив переписок для травли или давления; выдача себя за другого участника или администратора.
Наказание: мут, предупреждение или бан.

<b>8. КОНФЛИКТНЫЕ ТЕМЫ</b>
Запрещено провоцировать политические, религиозные и иные конфликты, разжигать ненависть и доводить обсуждения до травли. Администрация вправе ограничивать мешающие общению темы.

<b>9. МОРАЛЬНЫЕ НОРМЫ</b>
Чат — частное сообщество со своими моральными принципами. Мафиозник определяет допустимость контента и поведения. Администрация вправе удалять публикации и наказывать за нарушение норм, даже если случай не указан в правилах.

<b>10. ВЛАДЕЛЕЦ ЧАТА</b>
Мафиозник — высшая инстанция. Он вправе выдавать и отменять наказания; назначать и снимать должностных лиц; менять правила и модерацию; пересматривать решения администрации и ССС; наказывать без предварительного разбирательства.
Мафиозник не обязан публично объяснять каждое своё решение.

<b>11. АДМИНИСТРАЦИЯ</b>
Комиссары и другие уполномоченные лица вправе самостоятельно выдавать муты, предупреждения и баны в пределах своих полномочий.
О наказании они обязаны уведомить Мафиозника: указать участника, причину и меру. Мафиозник вправе изменить или отменить решение.

<b>12. ССС И ЭКСТРЕМАЛЬНЫЙ БАН</b>
ССС — коллегиальный орган рассмотрения нарушений, споров и апелляций. Его решения действуют внутри чата, но не ограничивают полномочия Мафиозника.
Экстремальный бан выдают Мафиозник, Кевин, Жоржи и комиссары за: сексуальные материалы с несовершеннолетними; порнографию и тяжёлый шок-контент; серьёзные угрозы; доксинг и кражу аккаунтов; тяжёлое мошенничество; обход бана; иные особо тяжкие нарушения.

<b>ЗАКЛЮЧИТЕЛЬНЫЕ ПОЛОЖЕНИЯ</b>
1. Правила обязательны для всех.
2. Незнание правил не освобождает от ответственности.
3. Удаление сообщения не отменяет наказание.
4. Обход бана — отдельное нарушение.
5. Администрация может обновлять правила.
6. Правила действуют с момента публикации.
7. Участие в чате означает согласие с ними.

<b>Мафиозник обладает высшей властью в управлении чатом.</b>"""


async def cmd_rules(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE
) -> None:
    msg = update.effective_message
    if not msg:
        return

    try:
        # Отправляем весь текст одним сообщением.
        await msg.reply_text(
            RULES_TEXT,
            parse_mode=ParseMode.HTML
        )

    except TelegramError:
        logger.exception("Не удалось отправить правила")

        try:
            await msg.reply_text(
                "⚠️ Не удалось отправить правила. "
                "Сообщи администрации."
            )
        except TelegramError:
            logger.exception("Не удалось отправить уведомление об ошибке")
