import logging
import re

from telegram import Update
from telegram.constants import ParseMode
from telegram.error import TelegramError
from telegram.ext import ContextTypes

logger = logging.getLogger(__name__)

RULES_RE = re.compile(r"(?i)^правила(\s+чата)?\s*[.!?]*\s*$")

RULES_TEXT = """<b>ПРАВИЛА ЧАТА</b>

<b>1. НАКАЗАНИЯ</b>
• Мут — временный запрет на сообщения.
• Предупреждение — действует 5 дней.
• 3 действующих предупреждения могут привести к бану.
• Бан — исключение из чата.
• Экстремальный бан — немедленное исключение за особо тяжкие нарушения.
Администрация вправе усиливать наказания с учётом обстоятельств.

<b>2. ОБЩЕНИЕ</b>
Запрещены:
• Оскорбления участников, родственников и близких.
• Травля, унижение и преследование.
• Провокации и намеренное разжигание конфликтов.
• Флуд, спам, массовые сообщения и упоминания.
• Злоупотребление капсом и засорение чата.
• Навязчивое общение после просьбы остановиться.
• Ложные обвинения и систематическое попрошайничество.

Наказание: замечание, мут, предупреждение или бан.

<b>3. ЗАПРЕЩЁННЫЙ КОНТЕНТ</b>
Запрещены:
• Порнография и сексуальные материалы с несовершеннолетними.
• Жестокие сцены, расчленение, пытки и шок-контент.
• Угрозы расправой и призывы к насилию.
• Нацизм, экстремизм, расовая ненависть и дискриминация.
• Оскорбление религиозных убеждений.
• Призывы к самоубийству и причинению себе вреда.
• Пропаганда жестокого обращения с животными.

Наказание: мут, бан или экстремальный бан.

<b>4. НИКОТИН И ЗАПРЕЩЁННЫЕ ТОВАРЫ</b>
Запрещены реклама, продажа, покупка, поиск продавцов и демонстративное продвижение:
• Снюса и никотиновых пакетиков.
• Сигарет, табака и вейпов.
• Жидкостей, картриджей и никотиновых смесей.
• Наркотиков, опасных веществ, нелегальных препаратов и оружия.

Демонстративное хвастовство наличием или употреблением такой продукции также может повлечь наказание.

Нейтральное информационное обсуждение само по себе не является нарушением.

Наказание: удаление сообщения, пред, мут или бан.

<b>5. РЕКЛАМА И ССЫЛКИ</b>
Запрещены:
• Реклама сторонних чатов, каналов, сайтов и услуг без разрешения.
• Самореклама и продвижение своих проектов.
• Реферальные и пригласительные ссылки без разрешения.
• Фишинг, мошеннические и вредоносные ссылки.
• Массовые упоминания для рекламы и спама.

Наказание: мут или бан.

<b>6. МОШЕННИЧЕСТВО</b>
Запрещены:
• Обман участников ради денег, монет или имущества.
• Мошенничество при сделках.
• Фальшивые сборы средств.
• Кража аккаунтов и выманивание кодов доступа.
• Использование багов бота для получения преимуществ.

Наказание: бан или экстремальный бан.

<b>7. ПРИВАТНОСТЬ</b>
Запрещены:
• Публикация личных данных без согласия.
• Доксинг и распространение конфиденциальной информации.
• Шантаж личными материалами.
• Слив переписок для травли или давления.
• Выдача себя за другого участника или администратора.

Наказание: мут, предупреждение или бан.

<b>8. КОНФЛИКТНЫЕ ТЕМЫ</b>
Запрещено намеренно провоцировать политические, религиозные и другие конфликты, разжигать ненависть и доводить обсуждения до травли.
Администрация вправе ограничивать темы, мешающие нормальному общению.

<b>9. МОРАЛЬНЫЕ НОРМЫ</b>
Чат является частным сообществом со своими моральными и этическими принципами.
Мафиозник вправе самостоятельно определять допустимость контента и поведения участников.

Администрация может удалять публикации и наказывать за поведение, противоречащее нормам сообщества, даже если конкретный случай прямо не перечислен в правилах.

<b>10. ВЛАДЕЛЕЦ ЧАТА</b>
Мафиозник — высшая административная инстанция.
Он вправе:
• Выдавать и отменять любые наказания.
• Назначать и снимать должностных лиц.
• Изменять правила и порядок модерации.
• Пересматривать решения администрации и ССС.
• Применять наказания без предварительного разбирательства.
Мафиозник не обязан публично объяснять каждое своё решение.

<b>11. АДМИНИСТРАЦИЯ</b>
Комиссары и другие уполномоченные лица вправе самостоятельно выдавать муты, предупреждения и баны в пределах своих полномочий.

После наказания они обязаны уведомить Мафиозника, указав участника, причину и вид наказания.
Мафиозник вправе отменить или изменить любое решение.

<b>12. ССС И ЭКСТРЕМАЛЬНЫЙ БАН</b>
ССС — коллегиальный орган рассмотрения нарушений, споров и апелляций.
Его решения действуют внутри чата, но не ограничивают полномочия Мафиозника.

Экстремальный бан могут выдавать Мафиозник, Кевин, Жоржи и комиссары.

Основания:
• Материалы сексуального характера с несовершеннолетними.
• Порнография и тяжёлый шок-контент.
• Серьёзные угрозы жизни и здоровью.
• Доксинг и кража аккаунтов.
• Тяжёлое мошенничество.
• Обход бана через другой аккаунт.
• Иные особо тяжкие нарушения.

<b>ЗАКЛЮЧИТЕЛЬНЫЕ ПОЛОЖЕНИЯ</b>
1. Правила обязательны для всех участников.
2. Незнание правил не освобождает от ответственности.
3. Удаление сообщения не отменяет наказание.
4. Обход блокировки считается отдельным нарушением.
5. Администрация вправе обновлять правила.
6. Правила вступают в силу после публикации.
7. Участие в чате означает согласие с правилами.

<b>Мафиозник обладает высшей властью в управлении чатом.</b>"""


async def cmd_rules(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    msg = update.effective_message
    if not msg:
        return

    try:
        await msg.reply_text(
            RULES_TEXT,
            parse_mode=ParseMode.HTML
        )
    except TelegramError as e:
        logger.warning("rules send: %s", e)
